"""
Step 3 - Clean the data (SQL does the work; Python runs it and validates).

Runs, in order:
    sql/00_ref_naics_sectors.sql   reference table of NAICS sectors
    sql/01_clean_base.sql          dedupe + types + wages + NYC flag
    sql/02_clean_employers.sql     employer name standardization
    sql/03_clean_roles_final.sql   role families, industry, final tables

Then runs validation checks and writes docs/validation_report.md:
    - row counts at every step (and asserts they reconcile)
    - wage flag counts + salary sanity by role family
    - role-family coverage and random spot-check samples
    - well-known employer spot-checks
    - employer merge log -> outputs/employer_merge_log.csv
"""
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "data" / "h1b.duckdb"
SQL_FILES = ["00_ref_naics_sectors.sql", "01_clean_base.sql",
             "02_clean_employers.sql", "03_clean_roles_final.sql"]

report: list[str] = []          # lines of the markdown report


def md_table(df) -> str:
    """DataFrame -> markdown table (avoids needing the 'tabulate' package)."""
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        cells = []
        for v in row:
            if isinstance(v, float):
                cells.append(f"{v:,.0f}" if abs(v) >= 100 else f"{v:.3f}")
            elif isinstance(v, int):
                cells.append(f"{v:,}")
            else:
                cells.append(str(v).replace("|", "/"))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def section(title: str, con, sql: str, note: str = ""):
    df = con.sql(sql).df()
    print(f"\n## {title}\n{df.to_string()}")
    report.extend([f"## {title}", ""] + ([note, ""] if note else []) + [md_table(df), ""])
    return df


def main():
    con = duckdb.connect(str(DB))
    for f in SQL_FILES:
        print(f"running {f} ...", flush=True)
        con.execute((ROOT / "sql" / f).read_text(encoding="utf-8")).fetchall()

    report.extend(["# Validation report (generated by src/03_clean.py)", "",
                   "Re-run `python src/03_clean.py` to regenerate. All numbers come straight from DuckDB.", ""])

    # ---------------- 1. Row counts at each step ----------------
    counts = section("1. Row counts through the pipeline", con, """
        SELECT 'lca_raw (all rows from 17 files)'          AS step, count(*) AS n_rows FROM lca_raw
        UNION ALL SELECT 'lca_dedup (one row per case_number)', count(*) FROM lca_dedup
        UNION ALL SELECT 'lca_all (typed, enriched)',            count(*) FROM lca_all
        UNION ALL SELECT 'lca_certified (Certified + H-1B)',     count(*) FROM lca_certified
        UNION ALL SELECT '  ...of which data roles',             count(*) FROM lca_certified WHERE is_data_role
        UNION ALL SELECT '  ...of which NYC data roles',         count(*) FROM lca_certified WHERE is_data_role AND is_nyc
    """)
    n = dict(zip(counts.step, counts.n_rows))
    distinct_cases = con.sql("SELECT count(DISTINCT case_number) FROM lca_raw").fetchall()[0][0]
    assert n["lca_dedup (one row per case_number)"] == distinct_cases, "dedup lost or kept extra cases"
    assert n["lca_all (typed, enriched)"] == distinct_cases, "a join duplicated rows in lca_all"

    section("2. Status x visa class (lca_all, after dedup)", con, """
        SELECT case_status, visa_class, count(*) AS n
        FROM lca_all GROUP BY ALL ORDER BY n DESC
    """, "Only `Certified` + `H-1B` goes into `lca_certified`.")

    section("3. Cases by fiscal year and quarter (lca_certified)", con, """
        SELECT fiscal_year, fiscal_quarter, count(*) AS n
        FROM lca_certified GROUP BY ALL ORDER BY ALL
    """, "Q3 (Apr-Jun) peaks every year: that is when employers file for the H-1B cap lottery winners. "
         "FY2026 has Q1-Q3 only (latest DOL file, through June 2026).")

    section("4. Type-conversion failures (should be ~0)", con, """
        SELECT
          sum((decision_date IS NULL)::INT)              AS null_decision_date,
          sum((annual_wage IS NULL)::INT)                AS null_annual_wage,
          sum((soc6 IS NULL OR soc6 = '')::INT)          AS bad_soc_code,
          sum((naics2 IS NULL)::INT)                     AS null_naics,
          sum((worksite_state IS NULL)::INT)             AS null_worksite_state
        FROM lca_certified
    """)

    # ---------------- 2. Wages ----------------
    section("5. Wage quality flags (lca_certified)", con, """
        SELECT
          count(*)                                        AS total,
          sum((NOT is_full_time)::INT)                    AS part_time,
          sum(flag_unit_suspect::INT)                     AS unit_suspect,
          sum(flag_wage_too_low::INT)                     AS below_30k,
          sum(flag_wage_too_high::INT)                    AS above_1m,
          sum(coalesce(flag_below_prevailing, false)::INT) AS below_95pct_prevailing,
          sum(wage_ok_for_stats::INT)                     AS usable_for_salary_stats,
          round(100.0 * sum(wage_ok_for_stats::INT) / count(*), 2) AS pct_usable
        FROM lca_certified
    """, "Flags can overlap. Rows failing any check are kept in the tables but excluded from salary statistics.")

    section("6. Wage unit mix (lca_certified)", con, """
        SELECT wage_unit, count(*) AS n, median(annual_wage) AS median_annualized
        FROM lca_certified GROUP BY 1 ORDER BY n DESC
    """)

    section("7. Salary sanity by role family (usable wages, all years)", con, """
        SELECT role_family, count(*) AS n,
               quantile_cont(annual_wage, 0.05) AS p05, quantile_cont(annual_wage, 0.25) AS p25,
               median(annual_wage) AS median,      quantile_cont(annual_wage, 0.75) AS p75,
               quantile_cont(annual_wage, 0.95) AS p95
        FROM lca_certified WHERE wage_ok_for_stats
        GROUP BY 1 ORDER BY median DESC
    """, "Expected shape: managers > scientists/engineers > analysts. Medians in the $80k-$200k range are plausible.")

    # ---------------- 3. Role families ----------------
    section("8. Role-family coverage by rule (lca_certified)", con, """
        SELECT role_rule, role_family, count(*) AS n,
               round(100.0 * count(*) / sum(count(*)) OVER (), 2) AS pct_of_all
        FROM lca_certified GROUP BY ALL ORDER BY role_rule
    """)

    section("9. How much of each data-related SOC code do we capture?", con, """
        SELECT soc_code, any_value(soc_title) AS soc_title, count(*) AS n,
               round(100.0 * avg(is_data_role::INT), 1) AS pct_classified_as_data_role
        FROM lca_certified
        WHERE soc_code IN ('15-2051.00','15-2051.01','15-2041.00','15-2041.01','15-1243.00',
                           '15-1243.01','15-1199.08','15-1199.07','15-2031.00','13-1161.00')
        GROUP BY 1 ORDER BY n DESC
    """, "Data Scientist SOC (15-2051.00) should be mostly captured. Operations research / market research SOCs "
         "are partly data roles and partly not, so lower capture is expected.")

    section("10. Top titles that matched NO rule but sit in data SOC codes (possible misses)", con, """
        SELECT job_title_upper, soc_code, count(*) AS n
        FROM lca_certified
        WHERE role_family = 'Other' AND soc6 IN ('15-2051', '15-2041')
        GROUP BY ALL ORDER BY n DESC LIMIT 25
    """, "Read this list to judge what the rules leave out. Most are deliberate exclusions (ML engineers, "
         "product managers, quants, statistical programmers) or titles too generic to call.")

    report.extend(["## 11. Random spot-check samples (20 per family, deterministic)", "",
                   "Manually reviewed. See the accuracy verdict in docs/DECISIONS.md.", ""])
    # Deterministic "random" sample: ordering by a hash of the case number
    # gives the same pseudo-random rows on every run. (DuckDB's USING SAMPLE
    # samples BEFORE the WHERE filter, which returned empty results here.)
    for fam in ["Data Analyst", "Business/BI Analyst", "Data Scientist", "Data Engineer",
                "Analytics Manager", "Other"]:
        df = con.sql(f"""
            SELECT job_title, soc_code, role_rule, employer_clean
            FROM lca_certified WHERE role_family = '{fam}'
            ORDER BY hash(case_number || 'spotcheck')
            LIMIT 20
        """).df()
        print(f"\n-- sample {fam}\n{df.to_string()}")
        report.extend([f"**{fam}**", "", md_table(df), ""])

    # ---------------- 4. Employers ----------------
    merges = con.sql("SELECT * FROM employer_merge_log").df()
    (ROOT / "outputs").mkdir(exist_ok=True)
    merges.to_csv(ROOT / "outputs" / "employer_merge_log.csv", index=False)
    section("12. Employer name standardization summary", con, """
        SELECT
          (SELECT count(DISTINCT employer_name)  FROM lca_all) AS raw_names,
          (SELECT count(DISTINCT norm1)          FROM employer_name_map) AS after_text_normalization,
          (SELECT count(DISTINCT norm2)          FROM employer_name_map) AS after_spacing_merge,
          (SELECT count(DISTINCT employer_clean) FROM employer_name_map) AS after_fein_merge,
          (SELECT count(DISTINCT employer_parent) FROM lca_all)          AS after_parent_rollup
    """)
    section("13. Largest employer merges (full list: outputs/employer_merge_log.csv)", con,
            "SELECT * FROM employer_merge_log ORDER BY n_rows DESC LIMIT 25")

    section("14. Well-known employer spot-checks (lca_certified, all years)", con, """
        SELECT employer_parent, count(*) AS all_lcas,
               sum(is_data_role::INT) AS data_role_lcas,
               count(DISTINCT employer_clean) AS legal_entities,
               mode(industry_sector) AS main_sector,
               median(annual_wage) FILTER (WHERE wage_ok_for_stats AND is_data_role) AS median_data_wage
        FROM lca_certified
        WHERE employer_parent IN ('AMAZON','GOOGLE','META','MICROSOFT','JPMORGAN CHASE',
                                  'GOLDMAN SACHS','DELOITTE','COGNIZANT','CAPITAL ONE','WALMART')
        GROUP BY 1 ORDER BY all_lcas DESC
    """, "Sanity check: Amazon, Google, Microsoft, Meta and the large IT-services firms should be at the top "
         "nationally, which matches public reporting on H-1B sponsors.")

    section("15. NYC flag check: top worksite cities/counties counted as NYC", con, """
        SELECT worksite_city, worksite_county, count(*) AS n
        FROM lca_certified WHERE is_nyc GROUP BY ALL ORDER BY n DESC LIMIT 12
    """)

    (ROOT / "docs" / "validation_report.md").write_text("\n".join(report), encoding="utf-8")
    print("\nwrote docs/validation_report.md")
    con.close()


if __name__ == "__main__":
    main()
